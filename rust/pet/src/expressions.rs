//! 表情语义 + LED 点阵模板
//!
//! 从 Flutter 侧移植：`expressions.dart`（语义枚举）与
//! `led_dot_renderer.dart` 的 `_outlines` / `_pupils`（点阵与瞳孔参数）。
//! 只眼模板 15×11，右眼水平镜像复用同一模板。

/// 表情语义（与 Flutter 侧 ExpressionType 一一对应）
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Expression {
    Neutral,
    Happy,
    Surprised,
    Angry,
    Sleepy,
    Love,
    Dead,
    Smug,
}

impl Expression {
    /// 全部表情（右键循环切换的顺序）
    pub const ALL: [Expression; 8] = [
        Expression::Neutral,
        Expression::Happy,
        Expression::Surprised,
        Expression::Angry,
        Expression::Sleepy,
        Expression::Love,
        Expression::Dead,
        Expression::Smug,
    ];

    /// 菜单/提示里显示的名字（P2 右键提示用）
    #[allow(dead_code)]
    pub fn label(self) -> &'static str {
        match self {
            Expression::Neutral => "平静",
            Expression::Happy => "开心",
            Expression::Surprised => "惊讶",
            Expression::Angry => "生气",
            Expression::Sleepy => "困",
            Expression::Love => "爱心",
            Expression::Dead => "死机",
            Expression::Smug => "得意",
        }
    }

    /// 在常量表中的下标
    pub fn index(self) -> usize {
        match self {
            Expression::Neutral => 0,
            Expression::Happy => 1,
            Expression::Surprised => 2,
            Expression::Angry => 3,
            Expression::Sleepy => 4,
            Expression::Love => 5,
            Expression::Dead => 6,
            Expression::Smug => 7,
        }
    }

    /// 下一个表情（循环）
    pub fn next(self) -> Expression {
        let all = Expression::ALL;
        all[(self.index() + 1) % all.len()]
    }
}

